export function t(clave, valores = {}) {
  const plantilla = TEXTOS[idioma][clave] ?? TEXTOS.es[clave] ?? clave;
  return plantilla.replace(/\{(\w+)\}/g, (_, k) => valores[k] ?? '');
}

